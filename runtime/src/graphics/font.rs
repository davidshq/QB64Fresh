/// Font constants
pub const FONT_WIDTH: u32 = 8;
pub const FONT_HEIGHT: u32 = 8;

/// Get the bitmap data for a character.
#[inline]
pub fn get_char_bitmap(ch: u8) -> &'static [u8; 8] {
    &FONT_8X8[ch as usize]
}

/// Check if a pixel is set in a character bitmap.
/// Row 0 is the top, column 0 is the leftmost bit (MSB).
#[inline]
pub fn is_pixel_set(bitmap: &[u8; 8], row: usize, col: usize) -> bool {
    if row >= 8 || col >= 8 {
        return false;
    }
    (bitmap[row] >> (7 - col)) & 1 != 0
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_font_size() {
        assert_eq!(FONT_8X8.len(), 256);
        for glyph in &FONT_8X8 {
            assert_eq!(glyph.len(), 8);
        }
    }

    #[test]
    fn test_space_is_blank() {
        let space = get_char_bitmap(b' ');
        for row in space {
            assert_eq!(*row, 0, "Space character should be all zeros");
        }
    }

    #[test]
    fn test_a_is_not_blank() {
        let a = get_char_bitmap(b'A');
        let sum: u16 = a.iter().map(|&b| b as u16).sum();
        assert!(sum > 0, "Letter A should have some pixels set");
    }

    #[test]
    fn test_is_pixel_set() {
        // Test with a known character - 'A' starts with 0x38 = 00111000
        let a = get_char_bitmap(b'A');
        assert_eq!(a[0], 0x38);
        assert!(!is_pixel_set(a, 0, 0)); // bit 7: 0
        assert!(!is_pixel_set(a, 0, 1)); // bit 6: 0
        assert!(is_pixel_set(a, 0, 2)); // bit 5: 1
        assert!(is_pixel_set(a, 0, 3)); // bit 4: 1
        assert!(is_pixel_set(a, 0, 4)); // bit 3: 1
        assert!(!is_pixel_set(a, 0, 5)); // bit 2: 0
        assert!(!is_pixel_set(a, 0, 6)); // bit 1: 0
        assert!(!is_pixel_set(a, 0, 7)); // bit 0: 0
    }

    #[test]
    fn test_bounds_checking() {
        let a = get_char_bitmap(b'A');
        assert!(!is_pixel_set(a, 8, 0)); // Row out of bounds
        assert!(!is_pixel_set(a, 0, 8)); // Column out of bounds
        assert!(!is_pixel_set(a, 100, 100)); // Both out of bounds
    }
}
