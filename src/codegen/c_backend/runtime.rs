    writeln!(
        output,
        "        if (len > 0 && buf[len-1] == '\\n') buf[--len] = '\\0';"
    )
    .unwrap();
    writeln!(output, "        *s = qb_string_new(buf);").unwrap();
    writeln!(output, "    }} else *s = qb_string_new(\"\");").unwrap();
